export const STEPS_PER_BAR = 16;

/**
 * Composite step activity for UI (any voice hits on this step).
 * @param {RhythmPattern['steps']} steps
 * @returns {number[]}
 */
export function compositeSteps(steps) {
  const composite = new Array(STEPS_PER_BAR).fill(0);
  for (const voice of Object.values(DRUM_VOICES)) {
    const row = steps[voice];
    if (!row) continue;
    for (let i = 0; i < STEPS_PER_BAR; i++) {
      if (row[i]) composite[i] = 1;
    }
  }
  return composite;
}
